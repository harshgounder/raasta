// the routing lane's format (app/route, "hroute"): network.geojson segments with tier + evidence[], barriers.json
// placements, meta.json, routes.json scenarios x leave_times x profiles. normalised here into the same shape as v1
const TYPE_MAP = { pole_obstruction: 'pole', missing_kerb_ramp: 'missing_ramp' }
const POSITIVE = new Set(['kerb_ramp_present', 'crossing_marked', 'clear'])
const PROFILE_LABEL = {
  manual_wheelchair: { en: 'manual wheelchair', hi: 'व्हीलचेयर' }, power_wheelchair: { en: 'power wheelchair', hi: 'बैटरी व्हीलचेयर' },
  walker_elderly: { en: 'walker (elderly)', hi: 'वॉकर (बुज़ुर्ग)' }, pram: { en: 'pram', hi: 'बच्चा गाड़ी' }, crutches: { en: 'crutches', hi: 'बैसाखी' },
  low_vision: { en: 'low vision', hi: 'कम दृष्टि' }, default_walker: { en: 'walking', hi: 'पैदल' },
}
// speeds only pace the route animation (an assumption, not used for any number shown)
const SPEED = { manual_wheelchair: 0.9, power_wheelchair: 1.2, walker_elderly: 0.6, pram: 1.0, crutches: 0.7, low_vision: 0.8, default_walker: 1.3 }
const urlIn = (s) => (String(s ?? '').match(/https?:\/\/[^\s)]+/) ?? [null])[0]
const hourOf = (iso) => { const m = String(iso).match(/T(\d\d):(\d\d)/); return m ? +m[1] + +m[2] / 60 : 0 }

function fromHroute(id, network, routesRaw, barriersRaw, meta) {
  const edges = [], clears = []
  for (const f of network.features ?? []) {
    if (f.geometry?.type !== 'LineString') continue
    const p = f.properties ?? {}, ev = p.evidence ?? []
    const neg = ev.filter((e) => !POSITIVE.has(e.type) && e.status === 'ACCEPT')
    const dates = ev.map((e) => e.observed_at).filter(Boolean).sort()
    // tiers (hroute v2): known_barrier | known_clear | osm_tag | unknown ('verified' kept for older files)
    const evidence = neg.length ? 'barrier' : (p.tier === 'known_clear' || p.tier === 'verified') ? 'clear' : 'unknown'
    // estimated = generated by the routing lane (sidewalk offsets, crossings, corners), NOT mapped in OSM: draw with EDGE_LEGEND.estimated
    edges.push({ id: p.id, tier: p.tier ?? null, estimated: p.source === 'generated', source: p.source, kind: p.kind, highway: p.highway, side: p.side, road_name: p.parent_road?.name || p.kind, length_m: p.length_m, evidence, observed: dates.at(-1) ?? null, note: p.note, path: f.geometry.coordinates, raw: ev })
  }
  const barriers = []
  for (const pl of barriersRaw?.placements ?? []) {
    const r = pl.record ?? {}
    const pos = r.lon != null ? [r.lon, r.lat] : null
    if (!pos) continue
    if (POSITIVE.has(pl.type)) { clears.push({ kind: 'clear', id: pl.record_id, segment_id: pl.segment_id, observed: r.observed_at, position: pos, label: r.label, raw: pl }); continue }
    barriers.push({ kind: 'barrier', id: pl.record_id, type: TYPE_MAP[pl.type] ?? pl.type, raw_type: pl.type, status: pl.status ?? pl.detection_status ?? 'ABSTAIN',
      confidence: r.confidence ?? null, segment_id: pl.segment_id, segment_p: pl.p ?? null, segment_alternatives: (pl.candidates ?? []).slice(0, 3).map((c) => ({ segment_id: c.segment_id, p: c.p })),
      height_cm: r.height_cm ?? null, height_err_cm: r.height_err_cm ?? null, observed: r.observed_at ?? null, photo: r.photo ?? null,
      source_url: urlIn(r.ref) ?? (r.source === 'project_sidewalk' ? 'https://sidewalk-chandigarh.cs.washington.edu' : null), credit: r.ref ?? r.label,
      abstain_reason: pl.status === 'ABSTAIN' ? pl.reason : null, label: r.label, origin: r.source ?? null, position: pos,
      // added for /map v2: the raw placement (candidates with at_m and side, evidence_photo, reason)
      raw: pl })
  }
  // segment evidence from the placements too (the network file may ship before evidence is attached to segments)
  const byId = new Map(edges.map((e) => [e.id, e]))
  for (const b of barriers) { const e = byId.get(b.segment_id); if (e && b.status === 'ACCEPT') { e.evidence = 'barrier'; if (!e.observed || (b.observed ?? '') > e.observed) e.observed = b.observed } }
  for (const c of clears) { const e = byId.get(c.segment_id); if (e && e.evidence === 'unknown') { e.evidence = 'clear'; e.observed = c.observed } }
  const profIds = routesRaw.profiles ?? []
  const profiles = profIds.map((p) => ({ id: p, label: PROFILE_LABEL[p] ?? { en: p.replace(/_/g, ' '), hi: p }, speed_mps: SPEED[p] ?? 1 }))
  const hours = (routesRaw.leave_times ?? []).map((lt) => [lt, hourOf(lt)]).sort((a, b) => a[1] - b[1])
  const win = (i) => [i === 0 ? 0 : (hours[i - 1][1] + hours[i][1]) / 2, i === hours.length - 1 ? 24 : (hours[i][1] + hours[i + 1][1]) / 2]
  const scenarios = (routesRaw.scenarios ?? []).map((sc) => {
    const routes = []
    hours.forEach(([lt], i) => {
      for (const [prof, x] of Object.entries(sc.routes?.[lt] ?? {})) for (const kind of ['shortest', 'accessible', 'least_blocked']) {
        const r = x[kind]; if (!r?.geometry?.coordinates?.length) continue
        routes.push({ id: `${sc.id}-${lt}-${prof}-${kind}`, kind, profile: prof, depart_hours: win(i), leave_time: lt, path: r.geometry.coordinates, length_m: r.length_m, minutes: r.minutes,
          barriers_hit: (r.barriers ?? []).map((b) => b.evidence_id ?? b.id), barrier_count: r.barrier_count ?? (r.barriers ?? []).length, blocking_count: r.blocking_count ?? (r.blocking ?? []).length, blocking: r.blocking ?? [], unknown_m: r.unknown_m ?? null, segments: r.segments, unknown_segments: r.unknown, verified_segments: (r.known_barrier ?? 0) + (r.known_clear ?? 0) || r.verified, tiers: r.tiers ?? null, what_if: !!r.what_if,
          // minutes is travel time. uncertainty_cost_s is a routing penalty, never shown as minutes; show unknown_share_pct instead
          minutes_detail: r.minutes_detail ?? null, unknown_share_pct: r.unknown_share_pct ?? null, mapped_m: r.mapped_m ?? null, estimated_m: r.estimated_m ?? null,
          barriers_observed: r.barriers_observed ?? null, evidence_line: r.evidence_line ?? null,
          // added for /map v2 (fields only): per-route block flag and the (cut to 40) barrier list
          blocked_for_profile: r.blocked_for_profile ?? null, barriers_list: r.barriers ?? [], uncertainty_cost_s: r.uncertainty_cost_s ?? null,
          summary: kind === 'shortest' ? r.summary : x.summary ?? r.summary, status: x.status })
      }
    })
    return { id: sc.id, name: sc.name, what_if: !!sc.what_if, note: sc.note ?? null, from: { label: sc.start?.label?.split(' (')[0] ?? 'start', lnglat: [sc.start?.lon, sc.start?.lat] }, to: { label: sc.end?.label?.split(' (')[0] ?? 'end', lnglat: [sc.end?.lon, sc.end?.lat] }, profiles, routes, leave_times: hours.map((h) => h[0]) }
  })
  const first = scenarios[0] ?? { profiles, routes: [] }
  return { id, meta: { name: meta.area ?? id, ...meta }, mock: false, format: 'hroute', edges, edgeById: new Map(edges.map((e) => [e.id, e])), barriers, clears,
    scenarios, routes: first, receipts: [], ledger: [], trips: null }
}

export async function loadCity(id) {
  if (cache.has(id)) return cache.get(id)
  const base = `/site-data/${encodeURIComponent(id)}`
  // only ask for files the index says exist (a 404 is a console error on stage)
  const files = (await cities()).find((c) => c.id === id)?.files
  const has = (f) => !files || files.includes(f)
  const getJsonIf = (f, fb) => (has(f) ? getJson(`${base}/${f}`, fb) : Promise.resolve(fb))
  const [network, routes, receipts, ledger, trips, meta, metaH, barriersH] = await Promise.all([
    getJson(`${base}/network.geojson`), getJsonIf('routes.json', { profiles: [], routes: [] }),
    getJsonIf('receipts.json', { receipts: [] }), getJsonIf('ledger.json', { entries: [] }),
    getJsonIf('trips.json', null), getJsonIf('city.json', null), getJsonIf('meta.json', null), getJsonIf('barriers.json', null),
  ])
  if (routes.scenarios || barriersH?.placements) {
    const city = fromHroute(id, network, routes, barriersH, metaH ?? {})
    city.receipts = receipts.receipts ?? []; city.ledger = ledger.entries ?? []; city.trips = trips
    cache.set(id, city); return city
  }
  const edges = [], barriers = [], clears = []
  for (const f of network.features ?? []) {
    const p = f.properties ?? {}
    if (p.kind === 'edge' || (f.geometry?.type === 'LineString' && !p.kind)) edges.push({ ...p, path: f.geometry.coordinates, evidence: p.evidence ?? 'unknown' })
    else if (p.kind === 'barrier') barriers.push({ ...p, position: f.geometry.coordinates })
    else if (p.kind === 'clear') clears.push({ ...p, position: f.geometry.coordinates })
  }
  const m = meta ?? {}
  const city = { id, meta: m, mock: !!(m.mock ?? network.properties?.mock), edges, edgeById: new Map(edges.map((e) => [e.id, e])), barriers, clears,
    routes, scenarios: null, receipts: receipts.receipts ?? [], ledger: ledger.entries ?? [], trips }
  cache.set(id, city)
  return city
}

// the routes to draw for a profile and a leave hour: the shortest, and the accessible one whose window holds the hour
export function pickRoutes(city, profile, hour) {
  const rs = city.routes.routes ?? []
  const inWin = (r) => { const [a, b] = r.depart_hours ?? [0, 24]; return hour >= a && hour < b }
  const shortest = rs.find((r) => r.kind === 'shortest' && (r.profile === 'any' || r.profile === profile) && inWin(r)) ?? rs.find((r) => r.kind === 'shortest')
  const accessible = rs.find((r) => r.kind === 'accessible' && r.profile === profile && inWin(r)) ?? null
  // no accessible route for this body: the least-blocked path, drawn with its blocking barriers
  const least_blocked = accessible ? null : rs.find((r) => r.kind === 'least_blocked' && r.profile === profile && inWin(r)) ?? null
  return { shortest, accessible, least_blocked }
}

export function fill(tpl, vars) { return (tpl ?? '').replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) }
export const hhmm = (h) => `${String(Math.floor(h) % 24).padStart(2, '0')}:${String(Math.round((h % 1) * 60)).padStart(2, '0')}`
