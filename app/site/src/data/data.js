// city data: /site-data/index.json lists the cities (vite.config.js builds it from app/site-data/<city>/);
// each city has network.geojson + routes.json (+ receipts.json, ledger.json, trips.json, city.json, all optional).
// schema v1 (made by tools/make_mock.py; the routing and /analyze lanes write the same shape):
//   edge    LineString { kind:'edge', id, source:'osm'|'generated', highway, side, road_name, length_m,
//                        evidence:'barrier'|'clear'|'unknown', observed:'YYYY-MM-DD'|null, barrier_ids:[] }
//   barrier Point      { kind:'barrier', id, type, status:'ACCEPT'|'ABSTAIN'|'REJECT', confidence, segment_id, segment_p,
//                        segment_alternatives:[{segment_id,p}], height_cm, height_err_cm, observed,
//                        photo:{url, crop:[x,y,w,h] in 0..1, credit, license}, source_url, detectors:{a:{label,score}, b:{...}} }
//   clear   Point      { kind:'clear', id, segment_id, observed, photo, source_url }
//   routes.json { profiles:[{id,label:{en,hi},speed_mps}], routes:[{id, kind:'shortest'|'accessible', profile:'any'|id,
//                 depart_hours:[from,to), path:[[lng,lat]], length_m, barriers_hit:[], barriers_avoided:[], unknown_m,
//                 summary:{en,hi} with {len} {extra} {n} {unknown} {profile} {time}, assumptions:[] }] }
const cache = new Map()
const getJson = async (url, fallback) => {
  try { const r = await fetch(url, { cache: 'no-cache' }); if (!r.ok || !/json/.test(r.headers.get('content-type') ?? 'json')) throw new Error(r.status); return await r.json() }
  catch (e) { if (fallback !== undefined) return fallback; throw new Error(`${url}: ${e.message}`) }
}
export const content = (name) => getJson(`/content/${name}.json`)

let index = null
export async function cities() {
  index ??= await getJson('/site-data/index.json', { cities: [] })
  return index.cities ?? []
}

