// reads the three recorded scans (public/content/scan-examples/*.json) and the impact matrix, and writes a small
// module for the /how page: per run the event clock, the counts at each gate, the impact rows with all 74 body
// verdicts, the receipt id. nothing is typed by hand here; rerun after the recordings change:
//   node app/site/how/tools/extract-runs.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SITE = join(HERE, '../..')
const REC = join(SITE, 'public/content/scan-examples')
const M = JSON.parse(readFileSync(join(SITE, 'public/content/impact-matrix.json'), 'utf8'))
const COUNTS = JSON.parse(readFileSync(join(SITE, '../route/taxonomy/COUNTS.json'), 'utf8'))

const elIndex = new Map(M.elements.map((id, i) => [id, i]))
const elInfo = new Map(M.element_info.map((e) => [e.id, e]))
const bodyTop = new Map(M.body_info.map((b) => [b.id, b.path[0]]))
const tops = Object.keys(M.body_tree)
const BODIES = M.bodies.map((id) => ({ id, top: bodyTop.get(id), name: M.body_info.find((b) => b.id === id)?.name ?? id }))
const CATS = M.element_tree.map((c) => ({ id: c.id, name: c.name, count: COUNTS.elements_per_category[c.id] ?? c.subcategories.reduce((a, s) => a + s.elements.length, 0) }))

const tally = (list) => list.reduce((a, d) => ((a[d.status] = (a[d.status] ?? 0) + 1), a), { ACCEPT: 0, ABSTAIN: 0, REJECT: 0 })
const r3 = (v) => (v == null ? null : Math.round(v * 1000) / 1000)

function run(file, id) {
  const d = JSON.parse(readFileSync(join(REC, file), 'utf8'))
  const ev = Object.fromEntries(d.events.map((e) => [e.stage, e]))
  const rc = ev.receipt.data
  const ag = ev.agreement.data.decisions
  const pol = ev.footpath_mask.data.policy
  const agree = tally(ag)
  const final = rc.counts
  const ctx = ev.impact.data.context
  const rows = (ev.impact.data.rows ?? []).map((r) => {
    const info = elInfo.get(r.matrix_id)
    return {
      id: r.id, matrix_id: r.matrix_id, name: r.matrix_name, status: r.status, from: r.from, source: r.matrix_source,
      category: info?.category ?? null, all: r.all_bodies,
      v74: elIndex.has(r.matrix_id) ? M.contexts[ctx].verdict[elIndex.get(r.matrix_id)] : null,
    }
  })
  const heights = (ev.measure.data.heights ?? []).map((h) => ({ class: h.class, status: h.height_status, cm: h.height_cm, why: (h.routes ?? []).map((x) => `${x.route}: ${x.why ?? (x.ok ? 'ok' : 'no')}`) }))
  return {
    id, label: d.label, file: d.image_file, source_url: d.source_url, licence: d.licence, recorded_at: d.recorded_at,
    client_total_s: d.client_total_s, server_total_s: ev.end.data.total_s,
    events: d.events.map((e) => ({ stage: e.stage, t: r3(e.t), c: r3(e.client_t), s: r3(e.data?.seconds ?? e.data?.wall_s ?? null) })),
    condition: ev.intake.data.condition.bin, light: ev.intake.data.condition.light, size: [ev.intake.data.w, ev.intake.data.h],
    detA: { n: ev.detector_a.data.boxes.length, s: ev.detector_a.data.seconds, prompts: ev.detector_a.data.prompts.length },
    detB: { n: ev.detector_b.data.boxes.length, s: ev.detector_b.data.seconds },
    links: ev.agreement.data.links.map((l) => ({ label: l.label, iou: l.iou })),
    agree, final,
    policy: pol.filter((p) => p.status !== 'REJECT').map((p) => ({ class: p.class, status: p.status, why: p.why, ground: p.footpath_context?.verdict ?? null })),
    shares: ev.footpath_mask.data.shares,
    depth: ev.depth.data.stats,
    horizon: ev.measure.data.horizon.source,
    heights,
    vlm: { model: ev.vlm.data.model, ok: ev.vlm.data.ok, error: ev.vlm.data.error, s: ev.vlm.data.wall_s ?? ev.vlm.data.seconds, sent: ev.vlm_start.data.boxes_sent.length },
    reasoner: { model: ev.reasoner.data.model, ok: ev.reasoner.data.ok, error: ev.reasoner.data.error },
    impact: { context: ctx, label: ev.impact.data.context_label, s: ev.impact.data.seconds, rows },
    placement: ev.placement.data.placement,
    receipt: { id: rc.id, schema: rc.schema, created_at: rc.created_at, image_id: rc.image.id, notes: rc.notes },
    timings: rc.timings, models: rc.models, thresholds: rc.thresholds,
  }
}

const RUNS = [
  run('street-cart-on-footpath.json', 'street'),
  run('hallway-hospital.json', 'hallway'),
  run('night-road-patna.json', 'night'),
]
const out = `// GENERATED by app/site/how/tools/extract-runs.mjs from public/content/scan-examples/*.json and impact-matrix.json.
// do not edit by hand; rerun the script.
export const RUNS = ${JSON.stringify(RUNS)}
export const BODIES = ${JSON.stringify(BODIES)}
export const BODY_TOPS = ${JSON.stringify(tops)}
export const CATS = ${JSON.stringify(CATS)}
`
writeFileSync(join(SITE, 'src/pages/how-runs.gen.js'), out)
console.log('wrote src/pages/how-runs.gen.js', out.length, 'bytes;', RUNS.map((r) => `${r.id} ${r.client_total_s}s ${JSON.stringify(r.final)}`).join(' | '))
console.log('body tops', tops.map((t) => `${t} ${BODIES.filter((b) => b.top === t).length}`).join(', '))
